/** `{var}` → `{{var}}` (i18next interpolation syntax). Skips already-`{{...}}` values. */
const convertInterpolation = (value: string) =>
  value.replace(/(?<!\{)\{([A-Za-z_][A-Za-z0-9_]*)\}(?!\})/g, "{{$1}}");

const deepConvert = (obj: any): any => {
  if (typeof obj === "string") return convertInterpolation(obj);
  if (Array.isArray(obj)) return obj.map(deepConvert);
  if (obj && typeof obj === "object") {
    const out: Dict = {};
    for (const k of Object.keys(obj)) out[k] = deepConvert(obj[k]);
    return out;
  }
  return obj;
};

/**
 * Merge with English as the structural base:
 * - keys present in both → deep-merge (partial value wins)
 * - keys only in base (missing translation) → keep base value
 * - keys only in partial (e.g. NEW keys) → add them
 */
const mergeWithBase = (base: any, partial: any): any => {
  if (partial === undefined) return base;
  if (Array.isArray(base)) return partial;
  if (base && typeof base === "object" && !Array.isArray(base)) {
    if (partial && typeof partial === "object" && !Array.isArray(partial)) {
      const out: Dict = { ...base };
      for (const k of Object.keys(partial)) {
        out[k] = k in base ? mergeWithBase(base[k], partial[k]) : partial[k];
      }
      return out;
    }
    return partial;
  }
  return partial;
};

// ─────────────────────────────────────────────────────────────────────────────
// 4. Build & write
// ─────────────────────────────────────────────────────────────────────────────

const NAMESPACES = ["common", "dashboard", "weather", "search", "profile", "auth", "calendar", "landing"] as const;
const OUT_DIR = join(__dirname, "..", "i18n", "locales");

const baseNs = buildNamespaces(LANG_FILES.en);

for (const lang of LANGS) {
  const langNs = buildNamespaces(LANG_FILES[lang]);
  const dir = join(OUT_DIR, lang);
  mkdirSync(dir, { recursive: true });

  for (const ns of NAMESPACES) {
    const merged = mergeWithBase(baseNs[ns], langNs[ns]);
    const withNew = mergeWithBase(merged, NEW_KEYS[lang][ns] ?? {});
    const final = deepConvert(withNew);
    writeFileSync(join(dir, `${ns}.json`), JSON.stringify(final, null, 2) + "\n");
  }
  console.log(`✔ wrote locales for "${lang}"`);
}

console.log(`Done — ${LANGS.length} languages × ${NAMESPACES.length} namespaces → ${OUT_DIR}`);

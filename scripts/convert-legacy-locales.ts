const pick = (obj: Dict, keys: readonly string[]) => {
  const out: Dict = {};
  for (const k of keys) if (k in obj) out[k] = obj[k];
  return out;
};

const omit = (obj: Dict, keys: readonly string[]) => {
  const out: Dict = { ...obj };
  for (const k of keys) delete out[k];
  return out;
};

